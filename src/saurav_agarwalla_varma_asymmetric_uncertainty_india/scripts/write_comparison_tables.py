"""Writes results/<run>/comparison.md with every table beside the paper."""

import argparse
import pathlib

from saurav_agarwalla_varma_asymmetric_uncertainty_india.earnings_options import (
    comparison_tables,
)


class WriteComparisonTablesApplication:
    """Command-line program that writes the comparison tables."""

    def run(self) -> None:
        """Writes the Markdown file.

        Raises:
            FileNotFoundError: If a result table is missing.
        """
        parser = argparse.ArgumentParser()
        parser.add_argument('--results', default='results/main')
        arguments = parser.parse_args()
        folder = pathlib.Path(arguments.results)
        tables = comparison_tables.ComparisonTables(folder)
        sections = [
            ('Table 1: the worked example (page 465)', tables.table_one()),
            (
                'Table 3: summary statistics (pages 469-470)',
                tables.table_three(),
            ),
            ('Table 4: correlations with SUE (page 470)', tables.table_four()),
            ('Table 5: smile levels by month (page 471)', tables.table_five()),
            ('Figures 3 and 4: key points', tables.figure_points()),
            ('Tables 6 to 9, SUE columns (pages 479-482)', tables.regression()),
            (
                'Tables 6 to 9 with P/C in notional value',
                tables.regression('tables_6_to_9_pc_value'),
            ),
            (
                'Tables 6 to 9 with the alternative SUE',
                tables.regression('tables_6_to_9_sue_alternative'),
            ),
        ]
        text = '# Comparison with the paper\n\n'
        text += (
            'Generated by scripts/write_comparison_tables.py. Stars: *** 1%, '
            '** 5%, * 10%, from classical standard errors as the paper appears '
            'to use; firm-clustered t-statistics are given in brackets.\n\n'
        )
        for title, body in sections:
            text += f'## {title}\n\n{body}\n\n'
        target = folder / 'comparison.md'
        target.write_text(text)
        print('wrote', target)


if __name__ == '__main__':
    WriteComparisonTablesApplication().run()
